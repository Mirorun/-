// ==========================================
// 2. 카카오톡 메시지 생성 도우미
// ==========================================
//
// ['날짜', '보낸 사람 ID', '대사']
//
// 날짜 예시:
// '2028-06-01T12:00:00+09:00'
//
// senderId 예시:
// 'yangyang' = 양양
// 'police' = 아름
// 'doctor' = 덕춘
//
// ==========================================

function makeMessages(chatId, history) {
  return history.map(([timestamp, senderId, text, type = 'text'], index) => ({
    id: `${chatId}-${String(index + 1).padStart(3, '0')}`,
    chatId,
    senderId,
    text,
    timestamp,
    type
  }));
}


